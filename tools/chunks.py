#!/usr/bin/env python3
"""
Level chunks.

Each chunk is 16 metatile columns by 13 rows and is theme independent: the
characters name a *role* ("solid ground", "one-way platform", "hazard") that
each theme fills with its own art.  Stages are assembled from sequences of
chunks, which keeps the levels hand-designed rather than random while making
eight stages of content tractable.

Legend
    '.'  open air                '#'  solid ground / rock
    '%'  solid structure         '='  one-way platform
    '-'  one-way platform (alt)  '^'  hazard (spikes)
    'x'  breakable block         '~'  water surface
    'w'  water body              'c'  climbable chain / vine
    '!'  stomp switch            '*'  checkpoint
    'X'  stage exit              'o'  solid prop  'O' solid prop 2
    'v'  prop platform           ','  scenery     "'" scenery 2
    '"'  scenery 3               'a'  backdrop A  'b' backdrop B
    'd'  backdrop C              'e'  backdrop D
    '1'-'6'  enemy roster slots  'k'  kickable object
    'g'  grabbable object        'h'  health pickup
    'p'  footwear pickup         'L'  extra life
    '@'  player start
"""

W = 16
H = 13


def C(*rows):
    assert len(rows) == H, "chunk needs %d rows, got %d" % (H, len(rows))
    for r in rows:
        assert len(r) == W, "row %r is %d wide" % (r, len(r))
    return list(rows)


CHUNKS = {}


def add(name, *rows):
    CHUNKS[name] = C(*rows)


